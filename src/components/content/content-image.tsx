import type { CSSProperties } from "react";
import variants from "../../../content/image-variants.json";

export type ContentImageData = {
  src: string;
  alt?: string;
  width?: number;
  height?: number;
  caption?: string;
};

type ImageVariants = {
  width: number;
  height: number;
  animated: boolean;
  variants: { width: number; src: string }[];
};

const manifest = variants as Record<string, ImageVariants>;

function decode(src: string) {
  try {
    return decodeURIComponent(src);
  } catch {
    return src;
  }
}

// srcset uses spaces and commas as separators, so each path segment must be encoded.
export function srcsetUrl(src: string) {
  return src.split("/").map((segment) => encodeURIComponent(decode(segment))).join("/");
}

/** Responsive WebP variants generated by `pnpm optimize:images`, if present. */
export function getImageVariants(src: string): ImageVariants | undefined {
  return manifest[decode(src.split(/[?#]/)[0])];
}

/** The largest optimized rendition, for lightboxes and other full-size views. */
export function getLargestImage(src: string) {
  return getImageVariants(src)?.variants.at(-1)?.src ?? src;
}

export function ContentImage({
  src,
  alt = "",
  width,
  height,
  className,
  style,
  loading = "lazy",
  sizes = "(max-width: 768px) 100vw, 1120px",
}: ContentImageData & {
  className?: string;
  sizes?: string;
  style?: CSSProperties;
  loading?: "eager" | "lazy";
}) {
  const normalizedSrc = src.startsWith("//") ? `https:${src}` : src;
  const optimized = getImageVariants(normalizedSrc);
  const intrinsicWidth = optimized?.width ?? width;
  const intrinsicHeight = optimized?.height ?? height;
  return (
    <img
      src={optimized?.variants.at(-1)?.src ?? normalizedSrc}
      srcSet={optimized?.variants.map((variant) => `${srcsetUrl(variant.src)} ${variant.width}w`).join(", ")}
      sizes={optimized ? sizes : undefined}
      alt={alt}
      width={width ?? intrinsicWidth}
      height={width && !height && intrinsicWidth && intrinsicHeight
        ? Math.round((width * intrinsicHeight) / intrinsicWidth)
        : height ?? intrinsicHeight}
      loading={loading}
      decoding="async"
      className={className}
      style={style}
    />
  );
}
